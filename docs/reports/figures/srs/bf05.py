"""BF-05 Breach & Force Majeure Resolution (activity diagram, UML / Visual Paradigm notation). 800 px wide."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from vpdiagram import Diagram  # noqa: E402

d = Diagram("bf05", width=800, height=1097)
for name, w in (("Buyer / Seller", 200), ("Arbitrator", 200), ("Inspector", 180), ("System", 220)):
    d.lane(name, w)
P, A, I, Y = (d.center(n) for n in ("Buyer / Seller", "Arbitrator", "Inspector", "System"))

d.initial("start", P, 55)
d.action("a1", P, 125, "1. Report a breach or\nclaim force majeure (or\nthe System detects a\nmissed obligation)", w=180)
d.action("a2", Y, 110, "2. Record the case and\nnotify the other party", w=200)
d.note("n2", 735, 180, "No penalty on\nan allegation", w=110)
d.action("a3", A, 220, "3. Review the evidence\nagainst the signed\nterms", w=180)
d.decision("d1", A, 285)
d.action("a4", A, 365, "4. Request an\ninspection per the\nsigned terms", w=160)
d.action("a5", I, 365, "5. Inspect and\nsubmit a report", w=160)
d.decision("m1", A, 435)
d.action("a6", A, 500, "6. Record the breaching\nparty and the evidence\nused", w=190)
d.action("a7", Y, 500, "7. Notify the parties and\nopen the 2-business-day\ncontest window", w=200)
d.note("n3", I, 585, "Penalty, forfeiture and\nlock wait; no-fault\nrefunds run at once", w=170)
d.decision("d2", Y, 655)
d.action("a8", P, 655, "8. Submit a contest\nwith evidence", w=180)
d.action("a9", I, 730, "9. Level 1.5 reviews\nthe case; the decision\nis final", w=170)
d.note("n4", I, 815, "Not available if the\ndecision already rests\non an inspection", w=170)
d.decision("m2", Y, 785)
d.action("a10", Y, 845, "10. Finalize the decision\nand execute the remedy", w=200)
d.decision("d3", Y, 905)
d.action("a11", Y, 997, "11. Settle the remaining\nscope, close the contract", w=200)
d.final_named("f1", Y, 1052, "Contract terminated", side="b")
d.final_named("f2", I, 905, "Contract stays active", side="b")

d.flow("start", "b", "a1", "t")
d.flow("a1", "r", "a2", "l", s_off=110 - 125)
d.edge("n2", "a2", d.nodes["n2"].port("t"), (735, d.nodes["a2"].box()[3]), dashed=True, arrow=False)
d.flow("a2", "b", "a3", "r", (630, 220), s_off=630 - Y)
d.flow("a3", "b", "d1", "t")
d.flow("d1", "b", "a4", "t", label="[inspection\nneeded]", label_at=(A - 75, 300))
d.flow("d1", "l", "m1", "l", (208, 285), (208, 435), label="[no]", label_at=(212, 267))
d.flow("a4", "r", "a5", "l")
d.flow("a5", "b", "m1", "r", (I, 435))
d.flow("m1", "b", "a6", "t")
d.flow("a6", "r", "a7", "l")
d.flow("a7", "b", "d2", "t")
d.edge("n3", "a7", d.nodes["n3"].port("r"), (630, 585), (630, d.nodes["a7"].box()[3]), dashed=True, arrow=False)
d.flow("d2", "l", "a8", "r", label="[the party at fault\ncontests in the window]", label_at=(A - 85, 625))
d.flow("a8", "b", "a9", "l", (P, 730))
d.edge("n4", "a9", d.nodes["n4"].port("t"), d.nodes["a9"].port("b"), dashed=True, arrow=False)
d.flow("a9", "r", "m2", "l", (620, 730), (620, 785))
d.flow("d2", "b", "m2", "t", label="[no contest]", label_at=(Y + 6, 671))
d.flow("m2", "b", "a10", "t")
d.flow("a10", "b", "d3", "t")
d.flow("d3", "b", "a11", "t", label="[material breach,\ntermination\nrequested]", label_at=(Y + 6, 923))
d.flow("a11", "b", "f1", "t")
d.flow("d3", "l", "f2", "r", label="[otherwise]", label_at=(I + 20, 887))

if __name__ == "__main__":
    d.write(Path(__file__).resolve().parent)
